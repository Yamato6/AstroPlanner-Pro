using System.ComponentModel.DataAnnotations;
using System.Globalization;
using System.Text;
using System.Text.Json.Serialization.Metadata;
using AstroPlanner.SkyBridge.App;

namespace AstroPlanner.BridgeGen;

/// <summary>
/// Writes src/web/packages/bridge-client/src/generated/contracts.ts from the app channel's C#
/// contracts: one zod schema and one TypeScript type per record, the method and event maps, the
/// error codes and the size limits. Records come from the JSON metadata of
/// <see cref="AppJsonContext"/> (wire names, nullability) and their DataAnnotations (constraints),
/// so the web UI validates exactly what the host does.
/// </summary>
public static class TypeScriptContracts
{
    /// <summary>The generated file, relative to the repository root.</summary>
    public const string RelativePath = "src/web/packages/bridge-client/src/generated/contracts.ts";

    public static string Generate()
    {
        var records = new List<JsonTypeInfo>();
        foreach (var method in AppMethods.All)
        {
            Collect(method.Request, records);
            Collect(method.Response, records);
        }

        foreach (var appEvent in AppEvents.All)
        {
            Collect(appEvent.Payload, records);
        }

        Collect(AppJsonContext.Default.RpcErrorPayload, records);

        var text = new StringBuilder();
        text.Append("""
            // Generated by tools/AstroPlanner.BridgeGen from src/AstroPlanner.SkyBridge/App (the C# records
            // are the source of truth). Do not edit: `dotnet run --project tools/AstroPlanner.BridgeGen`.
            import { z } from 'zod';

            """).Append('\n');
        text.Append(Invariant($"export const APP_PROTOCOL_VERSION = {AppMessageCodec.ProtocolVersion};\n\n"));
        text.Append("/** Largest messages (characters) the host accepts (requests) or sends (responses, events). */\n");
        text.Append("export const APP_LIMITS = {\n");
        text.Append(Invariant($"  maxRequestLength: {AppMessageCodec.MaximumRequestLength},\n"));
        text.Append(Invariant($"  maxResponseLength: {AppMessageCodec.MaximumResponseLength},\n"));
        text.Append(Invariant($"  maxEventLength: {AppMessageCodec.MaximumEventLength},\n"));
        text.Append("} as const;\n\n");
        var errorCodes = AppJsonContext.Default.RpcErrorPayload.Properties.Single(p => p.Name == "code")
            .AttributeProvider!.GetCustomAttributes(typeof(AllowedValuesAttribute), true).Cast<AllowedValuesAttribute>().Single().Values;
        text.Append("export const RPC_ERROR_CODES = [").Append(string.Join(", ", errorCodes.Select(Quote))).Append("] as const;\n");

        foreach (var record in records)
        {
            text.Append('\n');
            text.Append("export const ").Append(SchemaName(record.Type)).Append(" = z.strictObject({");
            if (record.Properties.Count > 0)
            {
                text.Append('\n');
                foreach (var property in record.Properties)
                {
                    text.Append("  ").Append(property.Name).Append(": ").Append(Zod(property)).Append(",\n");
                }
            }

            text.Append("});\n");
            text.Append("export type ").Append(record.Type.Name).Append(" = z.infer<typeof ").Append(SchemaName(record.Type)).Append(">;\n");
        }

        text.Append("\n/** Methods the web UI can call: request and response contracts. */\nexport const rpcMethods = {\n");
        foreach (var method in AppMethods.All)
        {
            text.Append("  ").Append(Quote(method.Name)).Append(": { request: ").Append(SchemaName(method.Request.Type))
                .Append(", response: ").Append(SchemaName(method.Response.Type)).Append(" },\n");
        }

        text.Append("} as const;\n\n/** Events the host pushes: payload contracts. */\nexport const appEvents = {\n");
        foreach (var appEvent in AppEvents.All)
        {
            text.Append("  ").Append(Quote(appEvent.Name)).Append(": ").Append(SchemaName(appEvent.Payload.Type)).Append(",\n");
        }

        text.Append("} as const;\n");
        // The raw string literal above takes this file's line endings: the output is always LF.
        return text.ToString().ReplaceLineEndings("\n");
    }

    /// <summary>Adds <paramref name="info"/> after the records it uses (depth first, once each).</summary>
    private static void Collect(JsonTypeInfo info, List<JsonTypeInfo> records)
    {
        if (records.Any(r => r.Type == info.Type))
        {
            return;
        }

        if (info.Kind != JsonTypeInfoKind.Object)
        {
            throw new NotSupportedException($"{info.Type.Name}: only records can be contracts.");
        }

        foreach (var property in info.Properties)
        {
            if (Element(property.PropertyType) is { } element && IsRecord(element))
            {
                Collect(AppJsonContext.Default.GetTypeInfo(element)!, records);
            }
        }

        records.Add(info);
    }

    private static string Zod(JsonPropertyInfo property)
    {
        var attributes = property.AttributeProvider?.GetCustomAttributes(true) ?? [];
        var underlying = Nullable.GetUnderlyingType(property.PropertyType);
        var expression = Base(underlying ?? property.PropertyType, attributes);
        return underlying is not null || property.IsGetNullable ? expression + ".nullable()" : expression;
    }

    private static string Base(Type type, object[] attributes)
    {
        if (type == typeof(string))
        {
            if (attributes.OfType<AllowedValuesAttribute>().SingleOrDefault() is { } allowed)
            {
                return "z.enum([" + string.Join(", ", allowed.Values.Select(Quote)) + "])";
            }

            var length = attributes.OfType<StringLengthAttribute>().SingleOrDefault();
            return "z.string()" + (length is null ? "" : Invariant($".min({length.MinimumLength}).max({length.MaximumLength})"));
        }

        if (type == typeof(int) || type == typeof(long))
        {
            return "z.int()" + RangeOf(attributes);
        }

        if (type == typeof(double))
        {
            return "z.number()" + RangeOf(attributes);
        }

        if (type == typeof(bool))
        {
            return "z.boolean()";
        }

        if (type != typeof(string) && Element(type) is { } element && element != type)
        {
            var length = attributes.OfType<LengthAttribute>().SingleOrDefault();
            return "z.array(" + Base(element, []) + ")" + (length is null ? "" : Invariant($".min({length.MinimumLength}).max({length.MaximumLength})"));
        }

        return IsRecord(type)
            ? SchemaName(type)
            : throw new NotSupportedException($"{type.Name} has no zod mapping; add one to {nameof(TypeScriptContracts)}.");
    }

    private static string RangeOf(object[] attributes) =>
        attributes.OfType<RangeAttribute>().SingleOrDefault() is { } range
            ? Invariant($".min({Number(range.Minimum)}).max({Number(range.Maximum)})")
            : "";

    private static string Number(object value) => Convert.ToDouble(value, CultureInfo.InvariantCulture).ToString("R", CultureInfo.InvariantCulture);

    /// <summary>The element type of a list or array, else the type itself.</summary>
    private static Type? Element(Type type)
    {
        if (type.IsArray)
        {
            return type.GetElementType();
        }

        var list = type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IReadOnlyList<>)
            ? type
            : type.GetInterfaces().FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IReadOnlyList<>));
        return list?.GetGenericArguments()[0] ?? type;
    }

    private static bool IsRecord(Type type) =>
        type.IsClass && type != typeof(string) && type.Namespace == typeof(AppInfoResponse).Namespace;

    private static string SchemaName(Type type) => char.ToLowerInvariant(type.Name[0]) + type.Name[1..] + "Schema";

    private static string Quote(object? value) => "'" + Convert.ToString(value, CultureInfo.InvariantCulture)!.Replace("'", "\\'", StringComparison.Ordinal) + "'";

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
